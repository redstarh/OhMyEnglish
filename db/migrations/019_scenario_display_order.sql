-- 대화 상황의 «노출 순서»를 담는 명시 컬럼을 둔다.
-- 결정: docs/ops/captain-instruction-register.md 「결정 81」(순서를 created_at 에서 떼어내
--   display_order 로 옮긴다) · 소유 태스크: TASK-130.1 · 회차:
--   tests/harness/runs/2026-09-12-task4-rotation-app-path.md §3-3
--
-- 번호: dev DB `schema_migrations` 직접 조회가 `001 · 003~007 · 009~018` 이므로 019 다(`H-AL`).
--
-- ⛔⛔ **무엇을 고치는가 — 게이트가 초록인 채 무너지는 부류다.**
-- 결정 76 이 「시드 배열 순서 = 노출 순서」로 정했고 그 순서를 `created_at` 이 담고 있었다. 그 컬럼의
-- 기본값은 `now()` 이고 PostgreSQL 의 `now()` 는 **트랜잭션 시작 시각에 고정**된다 ⇒ `seed()` 를 한
-- 트랜잭션으로 감싸면 30행이 같은 값을 받고 정렬이 뒷키(`id`)로 넘어간다. 실측한 크기: 창 10 안의
-- 계열 구성이 「일상 5·업무 3·여행 1·쇼핑 1」에서 **「일상 9·업무 1」**로 바뀐다(회차 §3-3).
--
-- ⛔ **두 번째 얼굴을 함께 닫는 것이 이 안을 고른 이유다.** `created_at` 은 upsert 로 갱신할 수 없어서
-- (갱신하면 «생성 시각»이 거짓이 된다) **시드 배열을 고쳐도 이미 시드된 DB 에는 반영되지 않았다** —
-- 2026-09-12 에 그 때문에 회차 하나를 버렸다(§3-2). 이 컬럼은 upsert 의 `set` 목록에 들어가므로
-- 배열 수정이 다음 `migrate.py` 실행에 반영된다.
--
-- ⛔ **`created_at` 을 UPDATE 하는 안을 기각했다**(결정 81 의 기각 ②). 이벤트 시각 컬럼에 합성한
-- 순서를 담으면 그 컬럼이 「그 행이 언제 생겼나」를 더 이상 말하지 않고, 배열을 고칠 때마다 저장된
-- `timestamptz` 를 고치게 된다 — 이 리포의 시각 규약이 금지하는 부류다.
--
-- ⚠️ **`default 0` 의 뜻**: 「시드 배열의 자리」이고 **시드가 아닌 행에는 뜻이 없다.** 사용자가 대화로
-- 만든 행(`source = 'generated'`)은 0 으로 남는다 — 고르는 규칙의 정렬 **맨 앞자리**가 이미
-- 「사용자가 만든 것인가」이므로(결정 80) 그 행들은 시드와 순서를 겨루지 않는다. 0 이 시드의 1..N
-- **앞**이라는 것도 그 결정과 같은 방향이다.
-- ⚠️ 생성 행끼리의 순서는 `created_at` 이 계속 가른다 — `_staleness` 가 `display_order` 뒤에 그 값을
-- 둘째 키로 두므로 「먼저 만든 것이 먼저」가 유지된다. 그 자리에서 `created_at` 은 **실제 생성 시각**
-- 이므로 이 마이그레이션이 없애려는 부류가 아니다.
--
-- ⚠️ 인덱스를 만들지 않는다 — 후보 표는 30행이고 고르는 규칙은 전체를 읽어 파이썬에서 정렬한다
-- (`services/scenario_rotation.pick_scenario`). 행이 수백으로 늘면 그때 재는 것이 순서다.
--
-- 되돌리기: 이 컬럼을 drop 하고 정렬을 `created_at` 으로 되돌린다(앱 4자리 · 계약 문면 1 · 테스트 5).
-- ⚠️ 되돌리면 위 두 결함이 함께 되살아난다 — 되돌리기 비용이 낮은 것이 위험이 낮다는 뜻은 아니다.

alter table learning_scenarios
  add column display_order int not null default 0;
